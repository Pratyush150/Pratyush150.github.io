/**
 * Scan public/media and emit src/content/media.generated.ts.
 *
 *   node scripts/gen-media-manifest.mjs
 *
 * Clips are produced by a separate render pipeline and may be absent. The
 * generated manifest is what lets <MediaWell> pick its degradation state at
 * build time, so a missing clip costs zero layout movement rather than a
 * runtime 404. Run this before `vite build`; `npm run build` already does.
 *
 * A file is only listed if it is non-empty — a half-written encode is treated
 * as absent, which is the honest reading of a zero-byte .webm.
 */
import { readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const mediaDir = fileURLToPath(new URL('../public/media/', import.meta.url));
const outPath = fileURLToPath(new URL('../src/content/media.generated.ts', import.meta.url));

if (!existsSync(mediaDir)) mkdirSync(mediaDir, { recursive: true });

const files = readdirSync(mediaDir).filter((f) => statSync(join(mediaDir, f)).size > 0);

/** id -> { webm, mp4, poster } */
const clips = {};
const put = (id, key, file) => {
  clips[id] ??= {};
  clips[id][key] = `/media/${file}`;
};

for (const f of files) {
  if (f.endsWith('-poster.jpg')) put(f.slice(0, -'-poster.jpg'.length), 'poster', f);
  else if (f.endsWith('-poster.webp')) put(f.slice(0, -'-poster.webp'.length), 'posterWebp', f);
  else if (f.endsWith('-poster.avif')) put(f.slice(0, -'-poster.avif'.length), 'posterAvif', f);
  else if (f.endsWith('.webm')) put(f.slice(0, -'.webm'.length), 'webm', f);
  else if (f.endsWith('.mp4')) put(f.slice(0, -'.mp4'.length), 'mp4', f);
}

const ids = Object.keys(clips).sort();
const body = `/* Generated by scripts/gen-media-manifest.mjs. Do not edit. */
export type ClipAssets = {
  webm?: string;
  mp4?: string;
  poster?: string;
  posterWebp?: string;
  posterAvif?: string;
};

export const MEDIA: Record<string, ClipAssets> = ${JSON.stringify(clips, null, 2)};

export const MEDIA_IDS: string[] = ${JSON.stringify(ids, null, 2)};
`;

writeFileSync(outPath, body);
const withVideo = ids.filter((id) => clips[id].webm || clips[id].mp4);
console.log(
  `media manifest: ${ids.length} entr${ids.length === 1 ? 'y' : 'ies'}, ` +
    `${withVideo.length} with a clip${ids.length ? ` (${ids.join(', ')})` : ''}`,
);
